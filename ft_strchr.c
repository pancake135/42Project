#include "libft.h"

char *strchr(const char *s, int c)
{
	while (*s != '\0')
	{
		if (*s == (char)c)
			return (s);
		s++;		
	}
	while ((char)c == '\0')
		return ((char *)s);
	return (NULL);
}
